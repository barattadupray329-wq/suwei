import { asc, eq } from 'drizzle-orm'
import { db } from '@/lib/db'
import { websitePackages } from '@/lib/db/schema'

export async function getPublicWebsitePackages() {
  try {
    return await db.query.websitePackages.findMany({
      where: eq(websitePackages.active, true),
      orderBy: [asc(websitePackages.sortOrder), asc(websitePackages.id)],
      limit: 4,
    })
  } catch (error) {
    const message = error instanceof Error ? `${error.message} ${error.cause ?? ''}` : String(error)
    if (process.env.NODE_ENV !== 'production' && message.includes('no such table: website_packages')) {
      return []
    }
    throw error
  }
}

