-- 清理合同 HT20260725-002 (id 1784969117370529) 因续租重复计费遗留的脏数据。
-- 背景：8/25~9/25 这个月被计了两次——系统自动生成的"逾期续租租金"账单(1787567190277047，已收¥90)
-- 与用户点续租又生成的重复"续租费"账单(1788250922956552，待收¥90)。用户此前手动把加在重复账单上的
-- ¥90收款冲正、并改收到逾期账单上，但重复账单本身仍以"待收款¥90"残留，且带着一条指向已冲正收款的
-- 无效分配(alloc 607)。这里把这条重复账单作废、清掉无效分配，并按真实账单/收款重算合同金额。

-- 1) 删除指向已冲正收款(1788083645118536)的无效分配（它当初分配在这条重复账单上）。
DELETE FROM payment_allocations WHERE id = 607;

-- 2) 作废重复的续租费账单（金额与已付逾期账单同月同额，属于重复计费）。
UPDATE receivable_bills
SET status = '已取消', notes = COALESCE(notes,'') || '｜系统清理：与逾期续租租金账单重复，已作废', updatedAt = CURRENT_TIMESTAMP
WHERE id = 1788250922956552 AND rentalId = 1784969117370529;

-- 3) 合同应收/已收重算：真实应收 = 3×110 + 续租费90(7/25) + 逾期续租租金90(8/25) = 510；
--    有效已收同为 510（¥330 + ¥90 + ¥90，冲正与再收互相抵消后净额）。全部结清。
UPDATE rentals
SET totalRent = '510.00', paidAmount = '510.00', paymentStatus = '已结清', updatedAt = CURRENT_TIMESTAMP
WHERE id = 1784969117370529;
